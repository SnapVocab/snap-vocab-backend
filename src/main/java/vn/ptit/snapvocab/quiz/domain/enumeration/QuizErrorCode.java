package vn.ptit.snapvocab.quiz.domain.enumeration;

import org.springframework.http.HttpStatus;

public enum QuizErrorCode {
	INVALID_REQUEST(HttpStatus.BAD_REQUEST),
	IDEMPOTENCY_KEY_REQUIRED(HttpStatus.BAD_REQUEST),
	QUIZ_NOT_FOUND(HttpStatus.NOT_FOUND),
	TOPIC_TEMPLATE_NOT_CONFIGURED(HttpStatus.UNPROCESSABLE_ENTITY),
	SEMANTIC_ROLE_NOT_BOUND(HttpStatus.UNPROCESSABLE_ENTITY),
	SEMANTIC_ROLE_AMBIGUOUS(HttpStatus.UNPROCESSABLE_ENTITY),
	QUIZ_INSUFFICIENT_ELIGIBLE_ITEMS(HttpStatus.UNPROCESSABLE_ENTITY),
	NOT_ENOUGH_DISTINCT_ANSWERS(HttpStatus.UNPROCESSABLE_ENTITY),
	INVALID_OPTION(HttpStatus.UNPROCESSABLE_ENTITY),
	INVALID_MATCHING_PAIR(HttpStatus.UNPROCESSABLE_ENTITY),
	QUESTION_ALREADY_CHECKED(HttpStatus.CONFLICT),
	MATCHING_LEFT_ALREADY_RESOLVED(HttpStatus.CONFLICT),
	MATCHING_TILE_ALREADY_MATCHED(HttpStatus.CONFLICT),
	QUIZ_NOT_IN_PROGRESS(HttpStatus.CONFLICT),
	QUIZ_HAS_UNRESOLVED_UNITS(HttpStatus.CONFLICT),
	QUIZ_NOT_FINISHED(HttpStatus.CONFLICT),
	QUIZ_SESSION_EXPIRED(HttpStatus.GONE);

	private final HttpStatus status;

	QuizErrorCode(HttpStatus status) {
		this.status = status;
	}

	public HttpStatus getStatus() {
		return status;
	}
}

